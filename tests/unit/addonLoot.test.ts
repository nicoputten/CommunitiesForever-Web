import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { parseLua } from "@/core/lua";
import { addonLootKey, addonLootLua, luaString } from "@/core/recipes/addonLoot";
import type { BossDropRecord, BossRecord } from "@/core/recipes/bosses";

// WEB-96: the addon's `Data\Loot.lua` (the shared dungeons contract, "Data contract 2"), from invented bosses and
// drops. tests/fixtures/addon-loot/Loot.lua is this output, a sample for the addon (CF-106); `UPDATE_LOOT_SAMPLE=1
// npx vitest run tests/unit/addonLoot.test.ts` writes it again after a deliberate change of the format.

const SAMPLE = path.join(__dirname, "../fixtures/addon-loot/Loot.lua");

const bosses: BossRecord[] = [
  { id: 9003, name: "Test Captain", dungeonId: "dm", position: 2, final: true, optional: false },
  { id: 9001, name: "Test Brute", dungeonId: "dm", position: 1, final: false, optional: false },
  { id: 9002, name: "Test Cook", dungeonId: "dm", position: 3, final: false, optional: true },
  { id: 9102, name: "Test Champion", dungeonId: "sm", wingId: "armory", position: 1, final: true, optional: false },
  { id: 9101, name: "Test Ghost", dungeonId: "sm", wingId: "graveyard", position: 1, final: true, optional: false },
  { id: 9150, name: "Test Warlord", dungeonId: "brs", wingId: "upper", position: 1, final: true, optional: false },
  { id: 9201, name: 'Test "Wolf" \\ the\nOld', dungeonId: "lordaeron", position: 1, final: true, optional: false },
  // The addon has no id for this dungeon: left out.
  { id: 9301, name: "Test Serpent", dungeonId: "drowned", position: 1, final: true, optional: false },
];
const drops: BossDropRecord[] = [
  { bossId: 9003, itemId: 7003, position: 1, chance: 40, classId: 4, subclassId: 4, classes: 1 },
  { bossId: 9003, itemId: 7005, position: 3, chance: 0.3, classId: 12, subclassId: 0, questId: 300 },
  { bossId: 9003, itemId: 7001, position: 2, chance: 12.3, classId: 2, subclassId: 4 },
  { bossId: 9001, itemId: 7006, position: 1, chance: 0.2, classId: 9, subclassId: 5, recipeId: 20001 },
  { bossId: 9102, itemId: 7001, position: 1, chance: 30, classId: 2, subclassId: 4 },
];
const input = { build: "1.60.1.70862", cmangos: "0123456789abcdef0123456789abcdef01234567", bosses, drops };
const lua = addonLootLua(input);
if (process.env.UPDATE_LOOT_SAMPLE === "1") writeFileSync(SAMPLE, lua);

/** The file as a value: the addon's `local _, ns = ...` / `ns.LootData =` read as one global. */
function parsed(text: string) {
  const body = text.replace("local _, ns = ...\nns.LootData = {", "LootData = {");
  return parseLua(body).globals.LootData as Record<string, unknown>;
}

describe("Data\\Loot.lua", () => {
  it("is the sample in tests/fixtures (the same data gives the same bytes)", () => {
    expect(lua).toBe(readFileSync(SAMPLE, "utf8").replace(/\r\n/g, "\n"));
    expect(addonLootLua({ ...input, bosses: [...bosses].reverse(), drops: [...drops].reverse() })).toBe(lua);
  });

  it("starts with the GPL-3.0 notice, the cmangos attribution, the build and a generated notice", () => {
    const header = lua.slice(0, lua.indexOf("local _, ns = ..."));
    expect(header.split("\n").every((l) => l === "" || l.startsWith("--"))).toBe(true);
    expect(header).toContain("GNU General Public License");
    expect(header).toContain("GPL-3.0");
    expect(header).toContain("cmangos classic-db, https://github.com/cmangos/classic-db");
    expect(header).toContain(input.cmangos);
    expect(header).toContain("build 1.60.1.70862");
    expect(header).toContain("Generated by CommunitiesForever-Web");
    expect(lua).toMatch(/\nlocal _, ns = \.\.\.\nns\.LootData = \{\n/);
    expect(lua.endsWith("}\n")).toBe(true);
  });

  it("parses: dungeons by the addon's id, bosses in order with final/optional, drops highest first", () => {
    const data = parsed(lua);
    expect(data.build).toBe("1.60.1.70862");
    const dungeons = data.dungeons as Record<string, unknown>;
    expect(Object.keys(dungeons)).toEqual(["dm", "smgy", "smarm", "ubrs", "lfg1982"]);
    expect(dungeons.dm).toEqual([
      {
        id: 9001,
        name: "Test Brute",
        drops: [{ item: 7006, chance: 0.2, cls: 9, sub: 5, recipe: 20001 }],
      },
      {
        id: 9003,
        name: "Test Captain",
        final: true,
        drops: [
          { item: 7003, chance: 40, cls: 4, sub: 4, classes: 1 },
          { item: 7001, chance: 12.3, cls: 2, sub: 4 },
          { item: 7005, chance: 0.3, cls: 12, sub: 0, quest: 300 },
        ],
      },
      // An empty table parses as an object.
      { id: 9002, name: "Test Cook", optional: true, drops: {} },
    ]);
    expect(dungeons.lfg1982).toEqual([{ id: 9201, name: 'Test "Wolf" \\ the\nOld', final: true, drops: {} }]);
  });

  it("the keys: a wing's own id, else the dungeon's; none for a dungeon the addon doesn't have", () => {
    expect(addonLootKey("sm", "cathedral")).toBe("smcath");
    expect(addonLootKey("brs", "lower")).toBe("lbrs");
    expect(addonLootKey("brs", "upper")).toBe("ubrs");
    expect(addonLootKey("thanes")).toBe("lfg1984");
    expect(addonLootKey("drowned")).toBeUndefined();
    expect(addonLootKey("nowhere")).toBeUndefined();
  });

  it("Lua 5.1 strings: quotes, backslashes and control characters escaped, other text as it is", () => {
    expect(luaString('a "b" \\ c\nd\re\u0001')).toBe('"a \\"b\\" \\\\ c\\nd\\013e\\001"');
    expect(luaString("Rhahk'Zor ’")).toBe(`"Rhahk'Zor ’"`);
  });
});
