// The addon's loot file, `Data\Loot.lua` (WEB-96; the shared dungeons contract, "Data contract 2"): the bosses of
// every dungeon the addon knows, with their own loot, generated from the item database by
// `npm run export:addon-loot` (scripts/export-addon-loot.ts) and committed to the addon at release. Pure and
// deterministic: the same data gives the same bytes. Lua 5.1: strings escaped, no long strings.
//
// The loot comes from cmangos classic-db (GPL-3.0), so this file is GPL-3.0 and says so; the addon's code stays MIT.
import { DUNGEONS } from "../gamedata/dungeons";
import type { BossDropRecord, BossRecord } from "./bosses";

export interface AddonLootInput {
  /** The Forever client build of the import (item_import.build). */
  build: string;
  /** The cmangos classic-db commit of the import. */
  cmangos: string;
  bosses: readonly BossRecord[];
  drops: readonly BossDropRecord[];
}

export interface AddonLootDungeon {
  /** The addon's dungeon id (Dungeons.STATIC id: "dm", "smarm", "lbrs", "lfg1982"). */
  key: string;
  bosses: { boss: BossRecord; drops: BossDropRecord[] }[];
}

/**
 * The addon's id of a dungeon or wing: the wing's own (Scarlet Monastery's smgy..smcath, Blackrock Spire's lbrs and
 * ubrs), else the dungeon's. Undefined for the dungeons the addon has no id for.
 */
export function addonLootKey(dungeonId: string, wingId?: string): string | undefined {
  const d = DUNGEONS.find((x) => x.id === dungeonId);
  if (d === undefined) return undefined;
  if (wingId !== undefined) return d.wings?.find((w) => w.id === wingId)?.addonId;
  return d.addonId;
}

/** The dungeons in the order of src/core/gamedata/dungeons.ts (wings in their order), bosses in the client's order. */
export function addonLootDungeons(bosses: readonly BossRecord[], drops: readonly BossDropRecord[]): AddonLootDungeon[] {
  const dropsOf = new Map<number, BossDropRecord[]>();
  for (const d of drops) (dropsOf.get(d.bossId) ?? dropsOf.set(d.bossId, []).get(d.bossId)!).push(d);
  const out: AddonLootDungeon[] = [];
  for (const d of DUNGEONS) {
    for (const wingId of d.wings?.map((w) => w.id) ?? [undefined]) {
      const mine = bosses
        .filter((b) => b.dungeonId === d.id && (wingId === undefined || b.wingId === wingId))
        .sort((a, b) => a.position - b.position || a.id - b.id);
      const key = addonLootKey(d.id, wingId);
      if (mine.length === 0 || key === undefined) continue;
      out.push({
        key,
        bosses: mine.map((boss) => ({
          boss,
          drops: [...(dropsOf.get(boss.id) ?? [])].sort((a, b) => a.position - b.position || a.itemId - b.itemId),
        })),
      });
    }
  }
  return out;
}

/** A Lua 5.1 string literal: quotes, backslashes and control characters escaped; other text as UTF-8. */
export function luaString(s: string): string {
  let out = '"';
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (ch === '"' || ch === "\\") out += `\\${ch}`;
    else if (ch === "\n") out += "\\n";
    else if (code < 0x20 || code === 0x7f) out += `\\${String(code).padStart(3, "0")}`;
    else out += ch;
  }
  return `${out}"`;
}

function luaKey(key: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : `[${luaString(key)}]`;
}

/** 36, 33.3, 0.5: whole numbers without a decimal point. */
function luaNumber(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`not a number: ${n}`);
  return Number.isInteger(n) ? String(n) : String(Math.round(n * 10) / 10);
}

