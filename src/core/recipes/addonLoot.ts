/** The whole `Data\Loot.lua`, "\n" line endings, ending in a newline. */
export function addonLootLua(input: AddonLootInput): string {
  const lines = [...HEADER(input.build, input.cmangos), "local _, ns = ...", "ns.LootData = {"];
  lines.push(`  build = ${luaString(input.build)},`, "  dungeons = {");
  for (const dungeon of addonLootDungeons(input.bosses, input.drops)) {
    lines.push(`    ${luaKey(dungeon.key)} = {`);
    for (const { boss, drops } of dungeon.bosses) {
      let head = `      { id = ${boss.id}, name = ${luaString(boss.name)}`;
      if (boss.final) head += ", final = true";
      if (boss.optional) head += ", optional = true";
      if (drops.length === 0) {
        lines.push(`${head}, drops = {} },`);
        continue;
      }
      lines.push(`${head}, drops = {`);
      for (const d of drops) {
        let row = `          { item = ${d.itemId}, chance = ${luaNumber(d.chance)}`;
        if (d.classId !== undefined) row += `, cls = ${d.classId}`;
        if (d.subclassId !== undefined) row += `, sub = ${d.subclassId}`;
        if (d.classes !== undefined) row += `, classes = ${d.classes}`;
        if (d.questId !== undefined) row += `, quest = ${d.questId}`;
        if (d.recipeId !== undefined) row += `, recipe = ${d.recipeId}`;
        lines.push(`${row} },`);
      }
      lines.push("      } },");
    }
    lines.push("    },");
  }
  lines.push("  },", "}", "");
  return lines.join("\n");
}
